import type { LatLng } from './plan'

/* 지도에게 시키는 일.
 *
 *  화면(View.tsx)은 어느 지도를 쓰는지 모른다. 아는 것은 이 여섯 가지뿐이다 —
 *  시야를 맞추고, 지날 자리를 미리 훑고, 지나온 길을 그리고, 사람을 옮기고,
 *  그 그림을 갈아 끼우고, 치운다. 그 밖에 이 화면이 지도에게 바라는 것은 없다. 마커도 클릭도
 *  없고, 이름표는 사람 그림 안에 함께 그린다.
 *
 *  **지도를 갈아끼우는 법.**
 *
 *  이 Canvas 를 구현한 파일을 하나 더 만들고(예: leaflet.ts), View.tsx 의
 *  import 한 줄을 그리로 돌리면 끝이다. 화면은 한 글자도 고치지 않는다.
 *
 *  지금 구현은 gmap.ts(구글 지도) 하나다. 일정 화면이 이미 구글을 쓰고 있어
 *  스크립트가 캐시에 남아 있고 생김새도 같은 결이라 그것으로 시작했을 뿐,
 *  이 화면이 구글에 매인 데는 없다 — 여기서 쓰는 것은 타일과 팬·줌과
 *  「좌표를 화면 픽셀로」뿐이고, 그것은 어느 지도에나 있다.
 */

/** 시야를 맞출 때 가장자리에 남길 자리(px). 사방이 같다 —
 *  한때 아래에 재생 막대가 누워 그쪽만 넓었지만, 막대는 걷어냈다. */
export type Pad = { top: number; bottom: number; left: number; right: number }

export type Canvas = {
  /** 사람을 화면 한가운데 두고, 화면에 이만큼(km)이 담기게 한다.
   *
   *  프레임마다 불린다. 중심은 늘 사람을 따라가고, 배율은 담을 폭이
   *  달라질 때만 손댄다.
   *
   *  **폭을 함께 받는 까닭.**
   *
   *  사람을 따라가기만 하면 화면이 감당 못 할 속도로 흐른다 — 구간을 화면에
   *  꽉 채우면 0.6초에 한 폭이 지나가(초당 167%) 지도가 타일을 받아 올 수
   *  없다. 그렇다고 카메라를 세워 두면 따라가는 느낌이 사라진다.
   *
   *  답은 배율이다. 빠른 구간은 넓게, 느린 구간은 가깝게 보면 화면에서는
   *  같은 속도로 흐른다. 신칸센이 초당 641km 라도 2100km 를 담으면 골목을
   *  걷는 것과 같은 빠르기로 보인다. 그 폭을 화면이 정해 넘긴다.
   *
   *  @param spanKm 화면의 짧은 쪽에 담을 거리 */
  follow(at: LatLng, spanKm: number): void
  /** 이 점들이 다 보이게 중심과 줌을 맞춘다. 다 보고 물러설 때 한 번 쓴다. */
  fit(pts: LatLng[], pad: Pad): void
  /** 지날 자리를 미리 훑어 타일을 받아 둔다.
   *
   *  지도의 타일 주소는 감춰져 있어 바로 내려받을 길이 없다. 브라우저
   *  곳간에 넣으려면 지도가 그 자리를 실제로 한 번 그려 봐야 한다.
   *
   *  다 받기를 기다리지는 않는다. 자리마다 잠깐 머물러 부르기만 시키고
   *  넘어간다 — 다 받을 때까지 기다리면 여는 데만 열 몇 초다. */
  warm(shots: { at: LatLng; span: number }[]): Promise<void>
  /** 지나온 길. 둘로 나눠 받는다.
   *
   *  @param done 이미 지난 구간들. 구간이 넘어갈 때만 바뀌므로 그때만 다시 그린다
   *  @param now  지금 지나는 구간에서 온 만큼. 프레임마다 바뀌지만 짧다
   *
   *  한 줄로 받던 때는 마흔두 초 뒤에 천육백 점짜리를 프레임마다 다시
   *  넘겼다 — 지도가 타일을 그릴 겨를이 없어 화면이 덜 그려졌다. */
  trail(done: LatLng[], now: LatLng[]): void
  /** 걷는 사람.
   *
   *  선과 같은 자리에 그려야 한다. 화면 한가운데에 CSS 로 못 박아 두었더니
   *  중앙은 지켜졌지만 선을 벗어났다 — 사람은 화면 좌표에, 선은 지도 좌표에
   *  있어 그리는 길이 서로 달랐기 때문이다. 지도가 한 박자 늦게 그려지는
   *  프레임마다 사람만 앞서 나갔다.
   *
   *  그래서 좌표를 받는다. 사람과 선이 같은 자리에 있으면 어긋날 수가 없고,
   *  한가운데에 두는 일은 follow 가 맡는다 — 지도의 한복판이 곧 사람이므로
   *  그려진 화면에서 사람은 늘 가운데다.
   *
   *  @param label 사람 위에 띄울 글자. 없으면 아무것도 띄우지 않는다
   *  @param show  거짓이면 감춘다. 다 보고 물러설 때 쓴다 —
   *               여정 전체를 보여 주는 화면에서는 사람이 설 자리가 없다 */
  walker(at: LatLng, label?: string, show?: boolean): void
  /** 걸어갈 그림을 갈아 끼운다.
   *
   *  walker 에 매 프레임 딸려 보내지 않는 까닭은, 이것이 초당 예순 번 물을
   *  값이 아니라 사람이 고를 때 한 번 바뀌는 값이기 때문이다.
   *
   *  @param src `data:` URL. null 이면 기본꼴(먹 원 안의 사람)로 돌아간다.
   *             밖을 가리키는 주소는 못 쓴다 — 마커가 이미지로 그려지는
   *             SVG 라 그 안에서 외부를 부르지 못한다(route/walkers.ts) */
  setWalker(src: string | null): void
  /** 지도와 그 위에 얹은 것을 다 걷는다 */
  destroy(): void
}

/** 지도를 el 안에 세운다. 스크립트를 받아 와야 하는 구현도 있으므로 약속이다.
 *  실패하면 거절한다 — 화면은 그때 「지도를 열지 못했다」를 띄운다. */
export type Mount = (el: HTMLElement) => Promise<Canvas>
